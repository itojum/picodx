require 'prism'
require 'set'

module PicoDX
  # Follows top-level require / require_relative statements from an entry file
  # and inlines the required files into a single Ruby script.
  #
  # PicoRuby.wasm starts with an empty virtual file system, so `require './foo'`
  # cannot load anything in the browser. Running a required file at runtime
  # (fetch + write to the virtual FS + load) is not an option either: when a
  # file being loaded awaits a real Promise (Image.load, Sound.new, fetch …),
  # the rest of that file is silently skipped. Resolving require at build time
  # avoids both problems.
  class Bundler
    class Error < StandardError; end

    REQUIRE_METHODS = %i[require require_relative].freeze

    # Libraries whose role PicoDX itself takes over; their require is dropped.
    DEFAULT_IGNORE = %w[dxruby].freeze

    Warning = Struct.new(:file, :line, :message) do
      def to_s = "#{file}:#{line}: #{message}"
    end

    attr_reader :files, :kept, :ignored, :warnings

    # root:       directory that `require './x'` is resolved against. Ruby
    #             resolves it against the current directory, and DXRuby games
    #             are started from their own folder, so this defaults to the
    #             entry file's directory.
    # load_paths: directories searched for `require 'x'` (default: [root]).
    #             A name not found there is left as a runtime require, which is
    #             how PicoRuby's built-in libraries such as 'js' are loaded.
    # ignore:     names whose require is removed (in addition to DEFAULT_IGNORE).
    def initialize(root: nil, load_paths: nil, ignore: [])
      @root       = root && File.expand_path(root)
      @load_paths = load_paths&.map { |dir| File.expand_path(dir) }
      @ignore     = (DEFAULT_IGNORE + ignore).map { |name| normalize_name(name) }.to_set
    end

    def bundle(entry)
      entry = File.expand_path(entry)
      raise Error, "entry file not found: #{entry}" unless File.file?(entry)

      @root ||= File.dirname(entry)
      @load_paths ||= [@root]
      @files    = []
      @loading  = []
      @kept     = []
      @ignored  = []
      @warnings = []

      header = "# Generated by `picodx bundle` from #{relative(entry)}. Do not edit.\n"
      header + expand(entry)
    end

    private

    def expand(path)
      @files << path
      @loading << path
      source = read(path)
      result = Prism.parse(source, filepath: path)
      unless result.errors.empty?
        error = result.errors.first
        raise Error, "#{relative(path)}:#{error.location.start_line}: syntax error: #{error.message}"
      end

      if result.data_loc
        warn_at(path, result.data_loc.start_line, '__END__ and the data after it are dropped (DATA is not available)')
        source = source.byteslice(0, result.data_loc.start_offset)
      end

      top_level = result.value.statements.body
      warn_nested_requires(path, top_level)

      out = +"# --- #{relative(path)} ---\n"
      cursor = 0
      top_level.each do |node|
        next unless require_call?(node)

        start  = node.location.start_offset
        finish = node.location.end_offset
        out << source.byteslice(cursor, start - cursor)
        out << replacement(path, node, source.byteslice(start, finish - start), line_start?(source, start))
        cursor = finish
      end
      out << source.byteslice(cursor, source.bytesize - cursor)
      out << "\n" unless out.end_with?("\n")
      out
    ensure
      @loading.pop
    end

    def replacement(path, node, original, at_line_start)
      method = node.name
      name   = node.arguments.arguments.first.unescaped.tr('\\', '/')

      if @ignore.include?(normalize_name(name))
        @ignored << name unless @ignored.include?(name)
        return "# (picodx bundle) ignored: #{original}"
      end

      target = resolve(path, method, name)
      if target.nil?
        # Not a file of this project: leave it to PicoRuby at runtime.
        return '' if @kept.include?(name)
        @kept << name
        return original
      end

      if @loading.include?(target)
        warn_at(path, node.location.start_line, "circular require of #{relative(target)} skipped")
        return ''
      end
      return '' if @files.include?(target)

      (at_line_start ? '' : "\n") + expand(target)
    end

    def resolve(path, method, name)
      file = name.end_with?('.rb') ? name : "#{name}.rb"

      if method == :require_relative
        candidate = File.expand_path(file, File.dirname(path))
      elsif file.start_with?('/')
        candidate = file
      elsif file.start_with?('./', '../')
        candidate = File.expand_path(file, @root)
      else
        return @load_paths.map { |dir| File.join(dir, file) }.find { |f| File.file?(f) }
      end

      return candidate if File.file?(candidate)

      raise Error, "#{relative(path)}: cannot find #{name.inspect} (#{method}) — " \
                   "looked for #{relative(candidate)}. Use --ignore #{name} to drop this require."
    end

    def require_call?(node)
      node.is_a?(Prism::CallNode) &&
        REQUIRE_METHODS.include?(node.name) &&
        node.receiver.nil? &&
        node.block.nil? &&
        node.arguments&.arguments&.size == 1 &&
        node.arguments.arguments.first.is_a?(Prism::StringNode)
    end

    # A require inside a method, block or condition cannot be inlined (it may
    # never run, or run many times), so it stays a runtime require — which
    # fails in the browser unless it names a built-in library.
    def warn_nested_requires(path, top_level)
      top_level.each do |node|
        next if require_call?(node)
        each_descendant(node) do |child|
          next unless child.is_a?(Prism::CallNode) && REQUIRE_METHODS.include?(child.name) && child.receiver.nil?
          warn_at(path, child.location.start_line, "#{child.name} is not at the top level, so it is not bundled")
        end
      end
    end

    def each_descendant(node, &block)
      node.compact_child_nodes.each do |child|
        yield child
        each_descendant(child, &block)
      end
    end

    def read(path)
      source = File.binread(path).force_encoding(Encoding::UTF_8)
      source = source.byteslice(3, source.bytesize - 3) if source.start_with?("﻿")
      raise Error, "#{relative(path)} is not valid UTF-8" unless source.valid_encoding?
      source
    end

    def line_start?(source, offset)
      offset.zero? || source.byteslice(offset - 1, 1) == "\n"
    end

    def normalize_name(name)
      name.tr('\\', '/').delete_suffix('.rb')
    end

    def warn_at(path, line, message)
      @warnings << Warning.new(relative(path), line, message)
    end

    def relative(path)
      base = @root || Dir.pwd
      path.start_with?("#{base}/") ? path.delete_prefix("#{base}/") : path
    end
  end
end
